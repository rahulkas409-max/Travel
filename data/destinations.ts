import type {
  Activity,
  ActivityKind,
  BudgetTier,
  Destination,
  Landscape,
  Occasion,
  Region,
  Rhythm,
  SlotType,
  Tier,
  Zone,
  ZoneLink,
} from "./types";

/* ──────────────────────────────────────────────────────────────────────────
 * Compact authoring helpers.
 *   A(slot, name, minutes, occasions, kind, costINR, tip, zone?)
 *   slot:      m = morning · a = afternoon · s = sunset · n = night
 *   occasions: R = romantic · C = corporate · S = school · F = solo/friends
 * ────────────────────────────────────────────────────────────────────────── */

type SlotCode = "m" | "a" | "s" | "n";
type Draft = Omit<Activity, "id">;

const SLOT: Record<SlotCode, SlotType> = { m: "morning", a: "afternoon", s: "sunset", n: "night" };
const OCC: Record<string, Occasion> = { R: "romantic", C: "corporate", S: "school", F: "solo" };

function A(
  slot: SlotCode,
  name: string,
  durationMins: number,
  occ: string,
  kind: ActivityKind,
  cost: number,
  tip: string,
  zone = "core",
): Draft {
  return {
    slot: SLOT[slot],
    name,
    durationMins,
    occasions: occ.split("").map((c) => OCC[c]).filter(Boolean),
    kind,
    cost,
    tip,
    zone,
  };
}

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);

interface Meta {
  id: string;
  name: string;
  aka?: string;
  region: Region;
  tier: Tier;
  state: string;
  tagline: string;
  tags: string[];
  elevation: number;
  idealMonths: string;
  landscapes: Landscape[];
  rhythms: Rhythm[];
  budgets?: BudgetTier[];
  occasions: string;
  imageKey: string;
  gateway: string;
  idealDays: [number, number];
  zones?: Zone[];
  zoneLinks?: ZoneLink[];
  scams?: string[];
  hospital?: string;
  farmhouseHub?: boolean;
}

function D(meta: Meta, highlights: Draft[]): Destination {
  const { occasions, budgets, ...rest } = meta;
  return {
    ...rest,
    budgets: budgets ?? ["backpacker", "boutique", "luxury"],
    occasions: occasions.split("").map((c) => OCC[c]).filter(Boolean),
    highlights: highlights.map((h) => ({ ...h, id: `${meta.id}-${slugify(h.name)}` })),
  };
}

